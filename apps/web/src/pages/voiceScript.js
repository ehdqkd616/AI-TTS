/** 한글 음절 수 → 낭독 시간 추정(초). 쉼 포함 초당 약 4음절 */
export const estimateSec = (text) => Math.round((text.match(/[가-힣]/g)?.length ?? 0) / 4);

/** 대본 전체를 텍스트 파일로 */
export function scriptAsText() {
  const lines = ['목소리 학습용 낭독 대본 (약 30분)', '', '[녹음 요령]', ...SCRIPT_TIPS.map((t) => `- ${t}`), ''];
  for (const s of SCRIPT) {
    lines.push(`──────── ${String(s.id).padStart(2, '0')}. ${s.title} (약 ${Math.round(estimateSec(s.text) / 60 * 10) / 10}분) ────────`, `· ${s.goal}`, '', s.text, '');
  }
  return lines.join('\n');
}
